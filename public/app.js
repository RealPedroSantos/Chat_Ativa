function createBulkController({
  id,
  container,
  itemLabel,
  endpoint,
  payloadKey = 'ids',
  reload,
  confirmText,
}) {
  const target = $(container)
  const toolbar = document.createElement('div')
  toolbar.id = `${id}-bulk-toolbar`
  toolbar.className = 'selection-toolbar hidden'
  toolbar.innerHTML = `
    <span><b data-bulk-count>0</b> selecionado(s)</span>
    <div>
      <button type="button" class="small secondary" data-bulk-all>Selecionar todos</button>
      <button type="button" class="small danger" data-bulk-delete>Excluir selecionados</button>
      <button type="button" class="small secondary" data-bulk-cancel>Cancelar</button>
    </div>`
  target.parentNode.insertBefore(toolbar, target)

  const controller = {
    id,
    selected: new Set(),
    allKeys: [],
    get mode() { return this.selected.size > 0 },
    apply() {
      toolbar.classList.toggle('hidden', !this.mode)
      toolbar.querySelector('[data-bulk-count]').textContent = this.selected.size
      for (const element of $$(`[data-bulk-controller="${id}"]`)) {
        const selected = this.selected.has(element.dataset.bulkKey)
        element.classList.toggle('selection-mode', this.mode)
        element.classList.toggle('selected', selected)
      }
    },
    toggle(key) {
      const value = String(key)
      if (this.selected.has(value)) this.selected.delete(value)
      else this.selected.add(value)
      this.apply()
    },
    setAllKeys(keys) {
      this.allKeys = keys.map(String)
      for (const key of [...this.selected]) if (!this.allKeys.includes(key)) this.selected.delete(key)
      this.apply()
    },
    clear() {
      this.selected.clear()
      this.apply()
    },
  }

  toolbar.querySelector('[data-bulk-all]').addEventListener('click', () => {
    for (const key of controller.allKeys) controller.selected.add(key)
    controller.apply()
  })
  toolbar.querySelector('[data-bulk-cancel]').addEventListener('click', () => controller.clear())
  toolbar.querySelector('[data-bulk-delete]').addEventListener('click', async () => {
    const values = [...controller.selected]
    if (!values.length) return
    const message = typeof confirmText === 'function' ? confirmText(values.length) : `Excluir ${values.length} ${itemLabel}?`
    if (!confirm(message)) return
    try {
      const payload = payloadKey === 'dates' ? values : values.map(Number)
      const result = await api(endpoint, {
        method: 'DELETE',
        body: JSON.stringify({ [payloadKey]: payload }),
      })
      controller.clear()
      await reload()
      notify(`${result.deleted ?? values.length} ${itemLabel} excluído(s).`)
    } catch (err) {
      notify(err.message, 'error')
    }
  })
  return controller
}

function wireBulkItem(element, key, controller, context = {}) {
  const value = String(key)
  element.dataset.bulkController = controller.id
  element.dataset.bulkKey = value
  if (!element.querySelector(':scope > .selection-check')) {
    const check = document.createElement('span')
    check.className = 'selection-check'
    check.setAttribute('aria-hidden', 'true')
    check.innerHTML = '<svg class="ui-icon" aria-hidden="true"><use href="icons.svg#i-check" /></svg>'
    element.prepend(check)
  }
  attachForcePress(element, (x, y) => openItemContextMenu({
    ...context,
    key: value,
    controller,
  }, x, y))
  element.addEventListener('click', (event) => {
    if (event.target.closest('button, input, select, label, textarea, a')) return
    if (Date.now() < suppressItemClickUntil) {
      event.preventDefault()
      event.stopImmediatePropagation()
      return
    }
    if (controller.mode) {
      event.preventDefault()
      event.stopImmediatePropagation()
      controller.toggle(value)
    }
  }, true)
  controller.apply()
}

