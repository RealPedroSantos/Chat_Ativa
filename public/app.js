$('#internal-record-audio').addEventListener('click', async () => {
  if (!currentInternalUserId) return
  if (internalMediaRecorder?.state === 'recording') {
    internalMediaRecorder.stop()
    return
  }
  if (!navigator.mediaDevices?.getUserMedia || !window.MediaRecorder) {
    notify('A gravação de áudio não é suportada neste navegador.', 'error')
    return
  }
  try {
    internalAudioStream = await navigator.mediaDevices.getUserMedia({ audio: true })
    const mimeType = recordingMimeType()
    const recorder = new MediaRecorder(internalAudioStream, mimeType ? { mimeType } : undefined)
    const chunks = []
    internalMediaRecorder = recorder
    recorder.addEventListener('dataavailable', (event) => {
      if (event.data.size) chunks.push(event.data)
    })
    recorder.addEventListener('stop', () => {
      const actualMime = recorder.mimeType || mimeType || 'audio/webm'
      const blob = new Blob(chunks, { type: actualMime })
      stopInternalRecording()
      if (blob.size) showInternalAudioPreview(blob, actualMime)
    }, { once: true })
    recorder.start(250)
    $('#internal-record-audio').classList.add('recording')
    $('#internal-record-audio').textContent = 'Parar'
  } catch (err) {
    stopInternalRecording()
    notify(err.name === 'NotAllowedError' ? 'Permita o uso do microfone para gravar áudio.' : 'Não foi possível iniciar a gravação.', 'error')
  }
})

