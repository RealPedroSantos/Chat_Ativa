function renderWaSync(wa) {
  const sync = wa.sync || {}
  const button = $('#btn-sync-wa')
  const status = sync.status || 'idle'
  const connectedEnough = ['connected', 'qr'].includes(wa.status)
  const busy = ['waiting_scan', 'syncing'].includes(status)
  button.disabled = !connectedEnough || busy
  button.textContent = status === 'waiting_scan'
    ? 'Aguardando leitura do QR Code…'
    : status === 'syncing'
      ? 'Sincronizando…'
      : status === 'complete'
        ? 'Sincronizar novamente'
        : 'Sincronizar agora'

  const labels = {
    idle: connectedEnough
      ? 'Pronto para importar. Você escolhe quando começar.'
      : 'Conecte o WhatsApp para liberar a sincronização.',
    waiting_scan: 'Autorização registrada. A sincronização começa assim que o QR Code for lido.',
    syncing: 'Organizando contatos e trazendo o histórico disponível…',
    complete: sync.lastSyncAt
      ? `Sincronização concluída em ${new Date(sync.lastSyncAt).toLocaleString('pt-BR')}.`
      : 'Sincronização concluída.',
    error: `Não foi possível concluir: ${sync.error || 'tente novamente.'}`,
  }
  $('#wa-sync-status-text').textContent = labels[status] || labels.idle
  $('#wa-sync-progress-bar').style.width = `${Math.max(0, Math.min(100, Number(sync.progress || 0)))}%`
  $('#sync-contacts').textContent = Number(sync.contactsImported || 0).toLocaleString('pt-BR')
  $('#sync-customers').textContent = Number(sync.customersCreated || 0).toLocaleString('pt-BR')
  $('#sync-messages').textContent = Number(sync.messagesImported || 0).toLocaleString('pt-BR')
  $('#wa-sync-status').classList.toggle('complete', status === 'complete')
  $('#wa-sync-status').classList.toggle('error', status === 'error')

  if (lastWaSyncStatus !== 'complete' && status === 'complete') {
    notify(`Sincronização concluída: ${Number(sync.contactsImported || 0)} contatos e ${Number(sync.messagesImported || 0)} mensagens importadas.`)
    loadContacts()
    if ($('#tab-customers').classList.contains('active')) loadCustomers()
  }
  lastWaSyncStatus = status
}

