function attachForcePress(element, openMenu, enabled = () => true) {
  element.addEventListener('contextmenu', (event) => {
    if (!enabled()) return
    event.preventDefault()
    openMenu(event.clientX, event.clientY)
  })

  let startX = 0
  let startY = 0
  let timer = null
  const cancel = () => {
    clearTimeout(timer)
    element.classList.remove('pressing')
  }
  element.addEventListener('pointerdown', (event) => {
    if (!enabled() || event.button !== 0 || event.target.closest('button, input, select, label, textarea, a')) return
    startX = event.clientX
    startY = event.clientY
    element.classList.add('pressing')
    clearTimeout(timer)
    timer = setTimeout(() => {
      suppressItemClickUntil = Date.now() + 900
      element.classList.remove('pressing')
      if (navigator.vibrate) navigator.vibrate(30)
      openMenu(startX, startY)
    }, 620)
  })
  element.addEventListener('pointermove', (event) => {
    if (Math.abs(event.clientX - startX) > 8 || Math.abs(event.clientY - startY) > 8) {
      cancel()
    }
  })
  for (const eventName of ['pointerup', 'pointercancel', 'pointerleave']) {
    element.addEventListener(eventName, cancel)
  }
}

