function beginAppointmentDrag(item, element) {
  draggedAppointmentId = item.id
  suppressCalendarClick = true
  element.classList.add('dragging')
  document.body.classList.add('calendar-is-dragging')
}

function endAppointmentDrag(element) {
  element.classList.remove('dragging')
  document.body.classList.remove('calendar-is-dragging')
  $$('.drag-over, .drop-target').forEach((target) => target.classList.remove('drag-over', 'drop-target'))
  setTimeout(() => {
    draggedAppointmentId = null
    suppressCalendarClick = false
  }, 80)
}

function makeAppointmentDraggable(element, item) {
  element.dataset.appointmentId = item.id
  let pointerDrag = null
  const targetAt = (event) => document.elementFromPoint(event.clientX, event.clientY)?.closest('.slot, .calendar-day')

  element.addEventListener('pointerdown', (event) => {
    if (event.button !== 0 || event.target.closest('button')) return
    pointerDrag = { pointerId: event.pointerId, startX: event.clientX, startY: event.clientY, active: false }
    element.setPointerCapture?.(event.pointerId)
  })
  element.addEventListener('pointermove', (event) => {
    if (!pointerDrag || pointerDrag.pointerId !== event.pointerId) return
    const distance = Math.hypot(event.clientX - pointerDrag.startX, event.clientY - pointerDrag.startY)
    if (!pointerDrag.active && distance < 7) return
    if (!pointerDrag.active) {
      pointerDrag.active = true
      beginAppointmentDrag(item, element)
    }
    event.preventDefault()
    $$('.drag-over, .drop-target').forEach((target) => target.classList.remove('drag-over', 'drop-target'))
    const target = targetAt(event)
    if (target?.classList.contains('slot')) target.classList.add('drop-target')
    else target?.classList.add('drag-over')
  })
  element.addEventListener('pointerup', (event) => {
    if (!pointerDrag || pointerDrag.pointerId !== event.pointerId) return
    const wasActive = pointerDrag.active
    const target = wasActive ? targetAt(event) : null
    pointerDrag = null
    element.releasePointerCapture?.(event.pointerId)
    if (!wasActive) return
    event.preventDefault()
    const slot = target?.closest('.slot')
    const day = target?.closest('.calendar-day')
    const date = slot ? ($('#appointment-form').elements.date.value || selectedCalendarDate) : day?.dataset.date
    const time = slot?.dataset.time || item.start_at.slice(11, 16)
    endAppointmentDrag(element)
    if (date) moveAppointment(item.id, date, time)
  })
  element.addEventListener('pointercancel', () => {
    if (pointerDrag?.active) endAppointmentDrag(element)
    pointerDrag = null
  })
}

