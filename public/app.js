function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))
}

// WhatsApp uses *text* for bold. Escape first so message content can never
// inject HTML, then add only the formatting tags generated by this function.
function formatMessageText(text) {
  return esc(text)
    .replace(/\*\*([^*\n]+?)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[\s(])\*([^*\n]+?)\*(?=$|[\s.,!?;:)])/g, '$1<strong>$2</strong>')
}

function notify(message, type = 'success') {
  const region = $('#toast-region')
  const toast = document.createElement('div')
  toast.className = `toast ${type}`
  toast.innerHTML = `<svg class="ui-icon" aria-hidden="true"><use href="icons.svg#${type === 'error' ? 'i-alert' : 'i-check'}" /></svg><span>${esc(message)}</span>`
  region.appendChild(toast)
  setTimeout(() => toast.remove(), 4200)
}

