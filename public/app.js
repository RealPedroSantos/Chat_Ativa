/* ---------- init ---------- */

async function init() {
  try {
    const state = await api('/api/state')
    applyPermissions(state.user, state.tenant, state.tenants)
    renderWaState(state.wa)
    if (['super_admin', 'admin'].includes(state.user.role)) renderAiConfigured(state.aiConfigured, state.apiKeySource)
    connectEvents()
    loadContacts()
    loadNoteCount()
    loadCalendarCount()
    const savedTab = localStorage.getItem('active-tab')
    const savedButton = savedTab ? $(`#tabs button[data-tab="${CSS.escape(savedTab)}"]:not(.hidden)`) : null
    const canOpenSaved = savedButton &&
      (!savedButton.hasAttribute('data-master') || ['super_admin', 'admin'].includes(CURRENT_USER?.role)) &&
      (!savedButton.hasAttribute('data-super') || CURRENT_USER?.role === 'super_admin')
    if (canOpenSaved) savedButton.click()
  } catch (err) {
    if (err.message !== 'unauthorized') console.error(err)
  }
}

;(async () => {
  try {
    const response = await fetch('/api/auth-status', { headers: TOKEN ? { 'x-auth-token': TOKEN } : {} })
    if (!response.ok) throw new Error(`Servidor indisponível (${response.status})`)
    const status = await response.json()
    if (status.setupRequired) showLogin('setup')
    else if (!status.user) showLogin('login')
    else init()
  } catch (err) {
    showLogin('login')
    $('#login-error').textContent = 'O painel web está publicado, mas o servidor permanente do WhatsApp ainda não foi conectado.'
    $('#login-form button[type="submit"]').disabled = true
    console.error(err)
  }
})()
