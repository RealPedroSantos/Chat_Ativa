function applyPermissions(user, tenant = null, tenants = []) {
  CURRENT_USER = user
  CURRENT_TENANT = tenant
  TENANTS = tenants || []
  const manager = ['super_admin', 'admin'].includes(user?.role)
  const superAdmin = user?.role === 'super_admin'
  $$('[data-master]').forEach((element) => element.classList.toggle('hidden', !manager))
  $$('[data-super]').forEach((element) => element.classList.toggle('hidden', !superAdmin))
  $$('[data-admin-only]').forEach((element) => element.classList.toggle('hidden', !manager || superAdmin))
  const roleLabel = superAdmin ? 'Super Master' : user?.role === 'admin' ? 'Admin' : 'Atendente'
  $('#current-user').textContent = user ? `${user.displayName} · ${roleLabel}${tenant ? ` · ${tenant.name}` : ''}` : ''
  $('#btn-logout').classList.toggle('hidden', !user)
  const activeMasterTab = $$('#tabs button[data-master]').find((button) => button.classList.contains('active'))
  const activeSuperTab = $$('#tabs button[data-super]').find((button) => button.classList.contains('active'))
  if (!manager || (!superAdmin && activeSuperTab)) {
    if (!manager && !superAdmin) {
      // Atendente: força sempre a aba Chats e limpa qualquer aba master salva
      const masterTabs = $$('#tabs button[data-master]').map((b) => b.dataset.tab)
      const saved = localStorage.getItem('active-tab')
      if (saved && masterTabs.includes(saved)) localStorage.removeItem('active-tab')
    }
    if ((!manager && activeMasterTab) || (!superAdmin && activeSuperTab)) $('#tabs button[data-tab=chats]').click()
  }
  renderTenantSwitcher()
  const adminOption = $('#user-form select[name=role] option[value=admin]')
  if (adminOption) adminOption.hidden = !superAdmin
}

