/* ---------- knowledge ---------- */

async function loadKnowledge() {
  const items = await api('/api/knowledge')
  const pending = items.filter((i) => i.status === 'pending')
  const approved = items.filter((i) => i.status === 'approved')
  knowledgeBulkController.setAllKeys(items.map((item) => item.id))

  const renderItem = (item, isPending) => {
    const div = document.createElement('div')
    div.className = 'item'
    div.innerHTML = `
      <div class="item-head">
        <span class="item-title">${esc(item.question)}</span>
        <span class="actions">
          ${isPending
            ? '<button class="small" data-act="approve">Aprovar</button><button class="small danger" data-act="reject">Rejeitar</button>'
            : '<button class="small danger" data-act="del">Excluir</button>'}
        </span>
      </div>
      <div class="item-body">${esc(item.answer)}</div>
      <div class="muted">${item.source === 'learned' ? 'Aprendido em conversa' : item.source === 'prompt' ? 'Sincronizado do prompt' : item.source === 'atendimento' ? 'Aprendido com atendente' : 'Cadastro manual'} · usado ${item.usage_count}x</div>`
    div.querySelector('[data-act=approve]')?.addEventListener('click', async () => {
      await api(`/api/knowledge/${item.id}/approve`, { method: 'POST' })
      loadKnowledge()
    })
    div.querySelector('[data-act=reject]')?.addEventListener('click', async () => {
      await api(`/api/knowledge/${item.id}/reject`, { method: 'POST' })
      loadKnowledge()
    })
    div.querySelector('[data-act=del]')?.addEventListener('click', async () => {
      if (confirm('Excluir este conhecimento?')) {
        await api('/api/knowledge/' + item.id, { method: 'DELETE' })
        loadKnowledge()
      }
    })
    const deleteOne = async () => {
      if (!confirm('Excluir este conhecimento?')) return
      try {
        await api('/api/knowledge/' + item.id, { method: 'DELETE' })
        loadKnowledge()
      } catch (err) {
        notify(err.message, 'error')
      }
    }
    wireBulkItem(div, item.id, knowledgeBulkController, {
      title: item.question,
      detail: item.answer,
      deleteOne,
    })
    return div
  }

  const pendingBox = $('#knowledge-pending')
  pendingBox.innerHTML = pending.length ? '' : '<p class="muted">Nenhum item pendente.</p>'
  pending.forEach((i) => pendingBox.appendChild(renderItem(i, true)))

  const approvedBox = $('#knowledge-approved')
  approvedBox.innerHTML = approved.length ? '' : '<p class="muted">Nenhum conhecimento aprovado ainda.</p>'
  approved.forEach((i) => approvedBox.appendChild(renderItem(i, false)))
}

$('#knowledge-form').addEventListener('submit', async (e) => {
  e.preventDefault()
  const data = formData(e.target)
  await api('/api/knowledge', { method: 'POST', body: JSON.stringify(data) })
  e.target.reset()
  loadKnowledge()
})

