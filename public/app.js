function notifyAppointmentUpdate(result, fallbackMessage) {
  const notification = result?.customerNotification
  if (notification?.status === 'sent') {
    notify(`${fallbackMessage} Cliente notificado pelo WhatsApp.`)
  } else if (notification?.status === 'queued') {
    notify(`${fallbackMessage} O aviso será enviado quando o WhatsApp estiver disponível.`)
  } else if (notification?.status === 'missing_phone') {
    notify(notification.message || 'Agendamento atualizado, mas não há telefone vinculado ao cliente.', 'error')
  } else {
    notify(fallbackMessage)
  }
}

