async function moveAppointment(id, date, time) {
  const item = calendarAppointments.find((appointment) => appointment.id === Number(id))
  if (!item) return
  try {
    const updated = await api(`/api/appointments/${item.id}`, {
      method: 'PUT',
      body: JSON.stringify({ date, time, duration: appointmentDuration(item) }),
    })
    selectedCalendarDate = date
    const movedDate = new Date(`${date}T12:00:00`)
    if (movedDate.getMonth() !== calendarCursor.getMonth() || movedDate.getFullYear() !== calendarCursor.getFullYear()) {
      calendarCursor = new Date(movedDate.getFullYear(), movedDate.getMonth(), 1)
    }
    resetAppointmentForm()
    notifyAppointmentUpdate(updated, `Agendamento movido para ${time}.`)
    await loadCalendar()
  } catch (err) {
    notify(err.message, 'error')
    await loadSlots()
  }
}

