function contactActivityTimestamp(contact) {
  const raw = String(contact?.last_message_at || contact?.created_at || '').trim()
  if (!raw) return 0
  const normalized = raw.includes('T') ? raw : `${raw.replace(' ', 'T')}Z`
  const timestamp = Date.parse(normalized)
  return Number.isFinite(timestamp) ? timestamp : 0
}

function sortContactsByRecent(items = []) {
  return [...items].sort((left, right) => {
    const timeDifference = contactActivityTimestamp(right) - contactActivityTimestamp(left)
    if (timeDifference) return timeDifference
    return String(left.name || left.jid).localeCompare(String(right.name || right.jid), 'pt-BR')
  })
}

