  chart.innerHTML = daily.length ? '' : '<div class="empty-state"><b>Sem consumo no período</b><small>O gráfico será preenchido após novas chamadas.</small></div>'
  const maxMetric = Math.max(0, ...daily.map((day) => Number(day.cost_usd) || Number(day.total_tokens) || 0))
  for (const day of daily) {
    const metric = Number(day.cost_usd) || Number(day.total_tokens) || 0
    const height = maxMetric > 0 ? Math.max(3, Math.round((metric / maxMetric) * 130)) : 3
    const column = document.createElement('div')
    column.className = 'chart-column'
    column.title = `${day.date}: ${compactNumber(day.total_tokens)} tokens · ${formatUsd(day.cost_usd)}`
    column.innerHTML = `<span class="chart-value">${Number(day.cost_usd) > 0 ? esc(formatUsd(day.cost_usd)) : compactNumber(day.total_tokens)}</span><span class="chart-bar" style="height:${height}px"></span><span class="chart-label">${esc(day.date.slice(8, 10) + '/' + day.date.slice(5, 7))}</span>`
    chart.appendChild(column)
  }

  const purposeList = $('#usage-purpose-list')
  purposeList.innerHTML = data.purposes?.length ? '' : '<p class="muted">Sem chamadas no período.</p>'
  for (const item of data.purposes || []) {
    const row = document.createElement('div')
    row.className = 'purpose-row'
    row.innerHTML = `<b>${esc(PURPOSE_LABEL[item.purpose] || item.purpose)}</b><strong>${esc(formatUsd(item.cost_usd))}</strong><small>${compactNumber(item.calls)} chamada(s) · ${compactNumber(item.total_tokens)} tokens</small>`
    purposeList.appendChild(row)
  }

  $('#usage-model-rows').innerHTML = (data.models || []).map((item) => `<tr><td><b>${esc(item.model)}</b></td><td>${compactNumber(item.calls)}</td><td>${compactNumber(item.prompt_tokens)}</td><td>${compactNumber(item.completion_tokens)}</td><td>${compactNumber(item.total_tokens)}</td><td>${esc(formatUsd(item.cost_usd))}</td></tr>`).join('') || '<tr><td colspan="6">Sem dados no período.</td></tr>'
