function cancelActiveRecording() {
  if (activeMediaRecorder?.state === 'recording') {
    discardActiveRecording = true
    activeMediaRecorder.stop()
  } else {
    stopRecordingUi()
  }
}

$('#chat-record-audio')?.addEventListener('click', async () => {
  if (activeMediaRecorder?.state === 'recording') {
    activeMediaRecorder.stop()
    return
  }
  if (!navigator.mediaDevices?.getUserMedia || !window.MediaRecorder) {
    notify('A gravação de áudio não é suportada neste navegador.', 'error')
    return
  }
  try {
    activeAudioStream = await navigator.mediaDevices.getUserMedia({ audio: true })
    const mimeType = recordingMimeType()
    const recorder = new MediaRecorder(activeAudioStream, mimeType ? { mimeType } : undefined)
    const chunks = []
    activeMediaRecorder = recorder
    recorder.addEventListener('dataavailable', (event) => {
      if (event.data.size) chunks.push(event.data)
    })
    recorder.addEventListener('stop', () => {
      const actualMime = recorder.mimeType || mimeType || 'audio/webm'
      const shouldDiscard = discardActiveRecording
      discardActiveRecording = false
      stopRecordingUi()
      activeMediaRecorder = null
      if (shouldDiscard) return
      const blob = new Blob(chunks, { type: actualMime })
      if (blob.size) showChatAudioPreview(blob, actualMime)
    }, { once: true })
    recorder.start(250)
    recordingStartedAt = Date.now()
    const button = $('#chat-record-audio')
    if (button) {
      button.classList.add('recording')
      button.setAttribute('aria-label', 'Parar e enviar áudio')
      recordingTimer = setInterval(() => {
        const seconds = Math.floor((Date.now() - recordingStartedAt) / 1000)
        button.textContent = `Parar ${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`
      }, 500)
      button.textContent = 'Parar 0:00'
    }
  } catch (err) {
    stopRecordingUi()
    activeMediaRecorder = null
    notify(err.name === 'NotAllowedError' ? 'Permita o uso do microfone para gravar áudio.' : 'Não foi possível iniciar a gravação.', 'error')
  }
})

