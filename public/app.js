const SOURCE_LABEL = { ai: 'IA', rule: 'Regra', canned: 'Resposta pronta', human: 'Manual', system: 'Sistema', user: '' }

function formatFileSize(value) {
  const bytes = Number(value || 0)
  if (!bytes) return ''
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
}

function messageMediaUrl(message) {
  return `/api/messages/${encodeURIComponent(message.id)}/media?token=${encodeURIComponent(TOKEN)}`
}

function renderMessageMedia(message) {
  if (!message.has_media) return ''
  const url = messageMediaUrl(message)
  const type = String(message.message_type || '')
  const mime = String(message.mime_type || '')
  const fileName = message.file_name || 'Arquivo'
  if (type === 'image' || type === 'sticker' || (type === 'gif' && mime.startsWith('image/'))) {
    return `<a class="msg-visual-link" href="${esc(url)}" target="_blank" rel="noopener" title="Abrir ${esc(fileName)}"><img class="msg-media ${type === 'sticker' ? 'sticker' : ''}" src="${esc(url)}" alt="${esc(type === 'sticker' ? 'Sticker' : fileName)}" loading="lazy" /></a>`
  }
  if (type === 'video' || type === 'gif') {
    const gifOptions = type === 'gif' ? 'autoplay loop muted playsinline' : 'controls preload="metadata" playsinline'
    return `<video class="msg-media" src="${esc(url)}" ${gifOptions} aria-label="${esc(fileName)}"></video>`
  }
  if (type === 'audio') {
    return `<div class="msg-audio${message.is_voice_note ? ' voice-note' : ''}"><span aria-hidden="true"><svg class="ui-icon"><use href="icons.svg#${message.is_voice_note ? 'i-mic' : 'i-music'}" /></svg></span><audio controls preload="metadata" src="${esc(url)}"></audio></div>`
  }
  return `<a class="msg-document" href="${esc(url)}" target="_blank" rel="noopener" download="${esc(fileName)}"><span class="msg-document-icon" aria-hidden="true"><svg class="ui-icon"><use href="icons.svg#i-file" /></svg></span><span><b>${esc(fileName)}</b><small>${esc(formatFileSize(message.file_size) || 'Arquivo')}</small></span><span class="msg-download-icon" aria-hidden="true"><svg class="ui-icon"><use href="icons.svg#i-download" /></svg></span></a>`
}

