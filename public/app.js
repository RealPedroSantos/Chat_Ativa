async function unlockNotificationAudio() {
  if (!calendarSoundEnabled) return null
  const AudioContextClass = window.AudioContext || window.webkitAudioContext
  if (!AudioContextClass) return null
  notificationAudioContext ||= new AudioContextClass()
  if (notificationAudioContext.state === 'suspended') await notificationAudioContext.resume().catch(() => {})
  return notificationAudioContext
}

async function unlockNotificationFiles() {
  if (!calendarSoundEnabled) return
  for (const audio of Object.values(notificationSounds)) {
    const previousVolume = audio.volume
    audio.volume = 0
    await audio.play().then(() => {
      audio.pause()
      audio.currentTime = 0
    }).catch(() => {})
    audio.volume = previousVolume
  }
}

function playNotificationSound(kind) {
  if (!calendarSoundEnabled || !notificationSounds[kind]) return
  const audio = notificationSounds[kind].cloneNode()
  audio.volume = 1
  audio.play().catch(() => {})
}

async function playAppointmentSound() {
  if (!calendarSoundEnabled) return
  const context = await unlockNotificationAudio()
  if (!context || context.state !== 'running') return
  const start = context.currentTime
  const notes = [659.25, 783.99, 987.77]
  notes.forEach((frequency, index) => {
    const oscillator = context.createOscillator()
    const gain = context.createGain()
    const noteStart = start + index * .11
    oscillator.type = 'sine'
    oscillator.frequency.setValueAtTime(frequency, noteStart)
    gain.gain.setValueAtTime(.0001, noteStart)
    gain.gain.exponentialRampToValueAtTime(.16, noteStart + .018)
    gain.gain.exponentialRampToValueAtTime(.0001, noteStart + .32)
    oscillator.connect(gain).connect(context.destination)
    oscillator.start(noteStart)
    oscillator.stop(noteStart + .34)
  })
}

