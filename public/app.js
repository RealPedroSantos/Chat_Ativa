function localIsoDate(date) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

function addDays(date, days) {
  const copy = new Date(date)
  copy.setDate(copy.getDate() + days)
  return copy
}

function calendarBounds() {
  const first = new Date(calendarCursor.getFullYear(), calendarCursor.getMonth(), 1)
  const gridStart = addDays(first, -first.getDay())
  return { start: localIsoDate(gridStart), end: localIsoDate(addDays(gridStart, 42)), gridStart }
}

function appointmentDuration(appointment) {
  return Math.round((new Date(appointment.end_at.replace(' ', 'T')) - new Date(appointment.start_at.replace(' ', 'T'))) / 60000)
}

