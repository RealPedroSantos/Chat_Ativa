async function loadCalendar() {
  const bounds = calendarBounds()
  const [appointments, exceptions] = await Promise.all([
    api(`/api/appointments?from=${bounds.start}&to=${bounds.end}`),
    api(`/api/calendar/exceptions?from=${bounds.start}&to=${bounds.end}`),
  ])
  calendarAppointments = appointments
  calendarExceptions = exceptions
  renderCalendarGrid(bounds.gridStart, exceptions)
  renderSelectedDay()
  loadWeeklyHours()
  renderExceptions(exceptions)
  loadCalendarCount()
}

function renderCalendarGrid(gridStart, exceptions) {
  $('#calendar-month-title').textContent = calendarCursor.toLocaleDateString('pt-BR', { month: 'long', year: 'numeric' })
  const grid = $('#calendar-grid')
  grid.innerHTML = ''
  const today = localIsoDate(new Date())
  for (let offset = 0; offset < 42; offset++) {
    const date = addDays(gridStart, offset)
    const iso = localIsoDate(date)
    const dayAppointments = calendarAppointments.filter((item) => item.start_at.startsWith(iso))
    const exception = exceptions.find((item) => item.date === iso)
    const div = document.createElement('div')
    div.dataset.date = iso
    div.className = 'calendar-day'
      + (date.getMonth() !== calendarCursor.getMonth() ? ' other' : '')
      + (iso === selectedCalendarDate ? ' selected' : '')
      + (iso === today ? ' today' : '')
    div.innerHTML = `<span class="day-number">${date.getDate()}</span>${exception ? `<span class="day-status ${exception.is_open ? 'open' : 'closed'}" title="${esc(exception.note || (exception.is_open ? 'Horário especial' : 'Fechado'))}" aria-label="${exception.is_open ? 'Horário especial' : 'Fechado'}"></span>` : ''}`
    for (const appointment of dayAppointments.slice(0, 3)) {
      const event = document.createElement('div')
      event.className = `day-event ${appointment.source}${appointment.status === 'cancelled' ? ' cancelled' : ''}`
      event.textContent = `${appointment.start_at.slice(11, 16)} ${appointment.customer_name}`
      event.title = 'Arraste para outro dia ou clique para editar'
      event.setAttribute('role', 'button')
      event.tabIndex = 0
      makeAppointmentDraggable(event, appointment)
      event.addEventListener('click', (clickEvent) => {
        clickEvent.stopPropagation()
        if (!suppressCalendarClick) editAppointment(appointment)
      })
      event.addEventListener('keydown', (keyEvent) => {
        if (keyEvent.key === 'Enter' || keyEvent.key === ' ') {
          keyEvent.preventDefault()
          editAppointment(appointment)
        }
      })
      div.appendChild(event)
    }
    if (dayAppointments.length > 3) {
      const more = document.createElement('div')
      more.className = 'muted'
      more.textContent = `+${dayAppointments.length - 3} compromisso(s)`
      div.appendChild(more)
    }
    div.addEventListener('click', () => {
      selectedCalendarDate = iso
      $('#appointment-form [name=date]').value = iso
      renderCalendarGrid(gridStart, exceptions)
      renderSelectedDay()
    })
    div.addEventListener('dragover', (event) => {
      if (!draggedAppointmentId) return
      event.preventDefault()
      event.dataTransfer.dropEffect = 'move'
      div.classList.add('drag-over')
    })
    div.addEventListener('dragleave', (event) => {
      if (!div.contains(event.relatedTarget)) div.classList.remove('drag-over')
    })
    div.addEventListener('drop', (event) => {
      event.preventDefault()
      div.classList.remove('drag-over')
      const id = event.dataTransfer.getData('text/plain') || draggedAppointmentId
      const item = calendarAppointments.find((appointment) => appointment.id === Number(id))
      if (item) moveAppointment(id, iso, item.start_at.slice(11, 16))
    })
    grid.appendChild(div)
  }
}

async function loadSlots(excludeAppointmentId = null) {
  const form = $('#appointment-form')
  const date = form.elements.date.value || selectedCalendarDate
  const duration = form.elements.duration.value || 60
  if (!date) return
  const id = excludeAppointmentId || form.elements.id.value
  const result = await api(`/api/calendar/slots?date=${date}&duration=${duration}${id ? `&excludeId=${id}` : ''}`).catch((err) => ({ open: false, slots: [], error: err.message }))
  const select = form.elements.time
  const selected = select.value
  select.innerHTML = '<option value="">Selecione</option>' + result.slots.map((slot) => `<option value="${slot}">${slot}</option>`).join('')
  if (result.slots.includes(selected)) select.value = selected
  const summary = $('#day-availability')
  summary.classList.toggle('closed', !result.open)
  summary.innerHTML = result.open
    ? `<b>${result.slots.length} horário(s) com vaga</b>${Number(result.capacity) > 1 ? `<div>Capacidade: até ${result.capacity} atendimentos simultâneos</div>` : ''}<div class="slots">${result.slots.map((slot) => `<button type="button" class="slot" data-time="${slot}" title="Selecionar ou mover para ${slot}">${slot}</button>`).join('')}</div>`
    : `<b>Fechado ou sem disponibilidade</b>${result.error ? `<div>${esc(result.error)}</div>` : ''}`
  $$('.slot').forEach((slot) => {
    slot.addEventListener('click', () => {
      select.value = slot.dataset.time
      syncSelectedSlot()
    })
    slot.addEventListener('dragover', (event) => {
      if (!draggedAppointmentId) return
      event.preventDefault()
      event.stopPropagation()
      event.dataTransfer.dropEffect = 'move'
      slot.classList.add('drop-target')
    })
    slot.addEventListener('dragleave', () => slot.classList.remove('drop-target'))
    slot.addEventListener('drop', (event) => {
      event.preventDefault()
      event.stopPropagation()
      slot.classList.remove('drop-target')
      const appointmentId = event.dataTransfer.getData('text/plain') || draggedAppointmentId
      moveAppointment(appointmentId, date, slot.dataset.time)
    })
  })
  syncSelectedSlot()
}

