async function uploadChatMedia(file, { voiceNote = false, preferredKind = '' } = {}) {
  if (!file || !currentJid) return
  const maxBytes = 25 * 1024 * 1024
  if (file.size > maxBytes) {
    notify('O arquivo excede o limite de 25 MB.', 'error')
    return
  }
  const input = $('#chat-input')
  const caption = voiceNote ? '' : input.value.trim()
  const name = file.name || (voiceNote ? 'mensagem-de-voz.webm' : 'arquivo')
  const mime = file.type || 'application/octet-stream'
  const preferredType = preferredKind || (/\.webp$/i.test(name) || mime === 'image/webp'
    ? 'sticker'
    : (/\.gif$/i.test(name) || mime === 'image/gif' ? 'gif' : ''))
  setChatUploadStatus(voiceNote ? 'Enviando mensagem de voz…' : `Enviando ${name}…`)
  try {
    const response = await fetch(`/api/send-media?jid=${encodeURIComponent(currentJid)}`, {
      method: 'POST',
      headers: {
        'x-auth-token': TOKEN,
        'Content-Type': 'application/octet-stream',
        'X-Media-Mime': encodeURIComponent(mime),
        'X-File-Name': encodeURIComponent(name),
        'X-Media-Caption': encodeURIComponent(caption),
        'X-Media-Kind': encodeURIComponent(preferredType),
        'X-Voice-Note': String(voiceNote),
      },
      body: file,
    })
    const result = await response.json().catch(() => ({}))
    if (!response.ok) throw new Error(result.error || 'Não foi possível enviar o arquivo.')
    if (caption) input.value = ''
    setChatUploadStatus('')
  } catch (err) {
    setChatUploadStatus('', true)
    notify('Falha ao enviar: ' + err.message, 'error')
  }
}

