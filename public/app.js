async function loadUsers() {
  if (!['super_admin', 'admin'].includes(CURRENT_USER?.role)) return
  const users = await api('/api/users')
  const box = $('#users-list')
  const selectableUsers = users.filter((user) => user.role !== 'super_admin' && user.id !== CURRENT_USER.id)
  userBulkController.setAllKeys(selectableUsers.map((user) => user.id))
  box.innerHTML = users.length ? '' : '<p class="muted">Nenhum usuário cadastrado.</p>'
  // Espelha a regra do servidor (server.js: "A empresa precisa manter pelo
  // menos um administrador ativo.") para avisar ANTES do clique, em vez de
  // deixar o usuário descobrir só depois que a exclusão foi recusada.
  const activeAdminCount = users.filter((u) => u.role === 'admin' && u.active).length
  for (const user of users) {
    const protectedSuper = user.role === 'super_admin'
    const lastActiveAdmin = user.role === 'admin' && user.active && activeAdminCount <= 1
    const canDelete = !protectedSuper && user.id !== CURRENT_USER.id && !lastActiveAdmin
    const div = document.createElement('div')
    div.className = 'item' + (user.active ? '' : ' disabled')
    div.innerHTML = `
      <div class="item-head">
        <div><span class="item-title">${esc(user.display_name)}</span> <span class="muted">@${esc(user.username)}</span></div>
        <span class="tag">${protectedSuper ? 'Super Master' : user.role === 'admin' ? 'Admin' : 'Atendente'}</span>
      </div>
      <div class="row compact user-controls">
        <label>Nome<input type="text" data-field="name" value="${esc(user.display_name)}" ${protectedSuper ? 'disabled' : ''} /></label>
        <label>Usuário<input type="text" data-field="username" value="${esc(user.username)}" autocomplete="username" ${protectedSuper ? 'disabled' : ''} /></label>
        <label>Permissão<select data-field="role" ${CURRENT_USER.role === 'admin' || protectedSuper ? 'disabled' : ''}><option value="attendant" ${user.role === 'attendant' ? 'selected' : ''}>Atendente</option><option value="admin" ${user.role === 'admin' ? 'selected' : ''}>Admin</option><option value="super_admin" ${protectedSuper ? 'selected' : ''}>Super Master</option></select></label>
        <label class="check"><input type="checkbox" data-field="active" ${user.active ? 'checked' : ''} ${protectedSuper ? 'disabled' : ''} /> Ativo</label>
      </div>
      <div class="actions">
        ${protectedSuper ? '<span class="muted">Conta global protegida</span>' : '<button class="small" data-act="save">Salvar</button><button class="small secondary" data-act="password">Trocar senha</button>'}
        ${canDelete ? '<button class="small danger" data-act="delete">Excluir</button>' : ''}
        ${!canDelete && user.id === CURRENT_USER.id ? '<span class="muted">usuário atual</span>' : ''}
        ${!canDelete && lastActiveAdmin && user.id !== CURRENT_USER.id ? '<span class="muted" title="A empresa precisa manter pelo menos um administrador ativo.">Único admin ativo — não pode ser excluído</span>' : ''}
      </div>`
    div.querySelector('[data-act=save]')?.addEventListener('click', async () => {
      await api(`/api/users/${user.id}`, {
        method: 'PUT',
        body: JSON.stringify({
          username: div.querySelector('[data-field=username]').value,
          displayName: div.querySelector('[data-field=name]').value,
          role: div.querySelector('[data-field=role]').value,
          active: div.querySelector('[data-field=active]').checked,
        }),
      })
      loadUsers()
    })
    div.querySelector('[data-act=password]')?.addEventListener('click', async () => {
      const password = prompt(`Nova senha para ${user.display_name} (mínimo 8 caracteres):`)
      if (!password) return
      await api(`/api/users/${user.id}/password`, { method: 'PUT', body: JSON.stringify({ password }) })
      notify('Senha atualizada.')
    })
    const deleteOne = async () => {
      if (!confirm(`Excluir o usuário ${user.display_name}?`)) return
      try {
        await api(`/api/users/${user.id}`, { method: 'DELETE' })
        loadUsers()
      } catch (err) {
        notify(err.message, 'error')
      }
    }
    div.querySelector('[data-act=delete]')?.addEventListener('click', deleteOne)
    if (!protectedSuper && user.id !== CURRENT_USER.id) {
      wireBulkItem(div, user.id, userBulkController, {
        title: user.display_name,
        detail: `@${user.username} · ${user.role === 'admin' ? 'Administrador' : 'Atendente'}`,
        deleteOne,
      })
    }
    box.appendChild(div)
  }
}

