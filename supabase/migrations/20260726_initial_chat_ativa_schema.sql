do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'tenants', 'global_settings', 'settings', 'contacts', 'customers',
    'messages', 'canned_responses', 'rules', 'knowledge', 'smart_notes',
    'smart_note_messages', 'users', 'conversation_cycles', 'internal_notes',
    'internal_messages', 'history_imports', 'weekly_availability',
    'calendar_exceptions', 'appointments', 'external_requests',
    'appointment_notifications', 'api_usage'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end
$$;
